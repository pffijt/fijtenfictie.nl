function openMenu() {
    const menuButtonElement = document.getElementById('menu-button');
    const menuElement = document.getElementById('menu');
    const menuContentElement = document.getElementById('menu-content');
    if (!menuContentElement.style.visibility || menuContentElement.style.visibility === 'hidden') {
        menuContentElement.style.visibility = 'visible';
        menuContentElement.style.opacity = 1;
        menuContentElement.style.height = 'auto';
        menuContentElement.style.width = 'auto';
        menuContentElement.style.bottom = 0;
        menuElement.parentElement.parentElement.style.width = '120px';
        menuElement.parentElement.parentElement.style.height = 'calc(42px * 6)';
        menuButtonElement.setAttribute('aria-expanded', 'true');
        menuElement.setAttribute('aria-hidden', 'false');
    } else {
        menuContentElement.style.visibility = 'hidden';
        menuContentElement.style.opacity = 0;
        menuContentElement.style.height = 0;
        menuContentElement.style.width = 0;
        menuElement.parentElement.parentElement.style.width = '85px';
        menuElement.parentElement.parentElement.style.height = '60px';
        menuButtonElement.setAttribute('aria-expanded', 'false');
        menuElement.setAttribute('aria-hidden', 'true');
    }
}

function getCurrentDate() {
    var d = new Date();
    let formatter = new Intl.DateTimeFormat('nl', {weekday: 'long', day: 'numeric', month: 'long', year: 'numeric'})
    var userReadableDate = formatter.format(d);
    document.getElementById("header-clock").innerHTML = "<time>"+userReadableDate+"</time>"
}

window.onload = function() {
    getCurrentDate();
    setInterval(() => {
        getCurrentDate();
    }, 60_000)
}

window.openMenu = openMenu;
window.getCurrentDate = getCurrentDate;

